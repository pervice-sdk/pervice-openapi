/// Generated source and the filename and directory used to save it.
typedef GeneratedFile = ({
  String name,
  String path,
  StringBuffer buffer,
});

/// Builds the context and generated source for enums, models, services and barrels.
final class OpenApiGenerator {
  const new({
    this.barrelGenerator = const .new(),
    this.enumGenerator = const .new(),
    this.modelGenerator = const .new(),
    this.serviceGenerator = const .new(),
  });

  final BarrelGenerator barrelGenerator;
  final EnumGenerator enumGenerator;
  final ModelGenerator modelGenerator;
  final ServiceGenerator serviceGenerator;

  /// Creates a source buffer with the generated file header.
  StringBuffer createStringBuffer() {
    final dateAt = DateFormat(DateFormat.YEAR_MONTH_DAY).format(.now());
    return StringBuffer(
      '// Generated by Pervice OpenAPI Generator on $dateAt\n'
      '// Do not edit this file manually.\n\n',
    );
  }

  /// Generates exports, Dio configuration and codec registration for one output.
  GeneratedFile generateBarrel({
    required Map<String, Schema> schemas,
    required Config config,
    required String barrelName,
    required List<String> exports,
  }) {
    final codecs = <String>[];

    for (final schema in schemas.entries) {
      // Select the generator and options for each schema.
      final (Generator<dynamic>, ConfigGenerator)? selection = schema.value.isEnum
          ? (enumGenerator, config.enumeration)
          : schema.value.isModel
          ? (modelGenerator, config.model)
          : null;

      if (selection == null) continue;

      // Skip generators without codecs.
      final (generator, options) = selection;
      if (!generator.hasCodec) continue;

      // Apply the configured prefix and suffix.
      final name = generator.typeName(
        schema.key,
        prefix: options.prefix,
        suffix: options.suffix,
      );

      codecs.add(name);
    }

    final BarrelGeneratorContext context = (
      barrelName: barrelName,
      exports: exports,
      codecs: codecs,
      buffer: createStringBuffer(),
    );

    barrelGenerator.generate(context);
    return (name: p.basenameWithoutExtension(barrelName), path: '', buffer: context.buffer);
  }

  /// Generates code and its output subdirectory for one enum schema.
  GeneratedFile generateEnum({
    required String name,
    required Schema schema,
    required Config config,
  }) {
    final EnumGeneratorContext context = (
      name: name,
      path: config.enumeration.path ?? 'enum',
      config: config,
      values: schema.enumValues!,
      buffer: createStringBuffer(),
    );

    enumGenerator.generate(context);
    return (name: name.snakeCase, path: context.path, buffer: context.buffer);
  }

  /// Generates code and its output subdirectory for one model schema.
  GeneratedFile generateModel({
    required String name,
    required Schema schema,
    required Map<String, Schema> schemas,
    required Config config,
    required String barrelName,
  }) {
    final ModelGeneratorContext context = (
      name: name,
      path: config.model.path ?? 'model',
      config: config,
      schema: schema,
      schemas: schemas,
      buffer: createStringBuffer(),
      barrelName: barrelName,
    );

    modelGenerator.generate(context);
    return (name: name.snakeCase, path: context.path, buffer: context.buffer);
  }

  /// Generates code and its output subdirectory for one service operation.
  GeneratedFile generateService({
    required OpenAPI openApi,
    required PathItem path,
    required Operation operation,
    required String method,
    required String url,
    required Config config,
    required String barrelName,
  }) {
    final name = switch (config.service.naming) {
      .operationId => operation.operationId ?? _serviceNameOf(method, url),
      .path => _serviceNameOf(method, url),
    };

    final ServiceGeneratorContext context = (
      name: name,
      path: config.service.path ?? 'service',
      config: config,
      schema: openApi.responseSchema(operation),
      schemas: openApi.components?.schemas ?? {},
      buffer: createStringBuffer(),
      barrelName: barrelName,
      operation: operation,
      method: method,
      url: url,
      parameters: openApi.parameters(path, operation),
    );

    serviceGenerator.generate(context);
    return (name: name.snakeCase, path: context.path, buffer: context.buffer);
  }

  /// Builds a method and path name, turning path parameters into By segments.
  String _serviceNameOf(String method, String url) {
    final segments = Uri(path: url).pathSegments.map((segment) {
      return segment.startsWith('{') ? 'by_${segment.substring(1, segment.length - 1)}' : segment;
    });

    return [method, ...segments].join('_').pascalCase;
  }
}
